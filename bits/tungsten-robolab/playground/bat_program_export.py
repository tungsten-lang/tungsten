"""Export ideal-control swings (playground/bat_ceiling.py results) as the v6
batter's feed-forward swing program, lib/robolab/skills/bat_program.w.

    .venv/bin/python playground/bat_program_export.py out/bat_ceiling/a.json [b.json ...] [--out lib/robolab/skills/bat_program.w]

Each ceiling run is one pitch location (its seed's crossing point in the
18-pitch sweep: x from the plate centre, z height at the front of the plate):
its program is the per-knot net excitation u of each joint, the joint's
displacement from the program's start every control tick, and the program
time at which it met the pitch. The skill (skills/bat_power.w, `prog`) plays
the excitations as drive and the displacements as the reflex target, blending
the programs by inverse squared distance to the pitch's predicted crossing
(exactly a program's own at its location).
"""

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "tasks"))


PLATE_FRONT_Y = -0.215
SPEED_SCALE = 0.02   # m of crossing distance per m/s of pitch speed, for the blend


def pitch_location(seed):
    os.environ.setdefault("BAT_BODY", "athlete")
    import bat as battask
    grid = [(v, x, z) for v in battask.SWEEP_SPEEDS for x, z in battask.SWEEP_LOCS]
    v, x, z = grid[int(seed) % len(grid)]
    return x, z


def fmt(xs):
    return "[" + ", ".join(f"~{x:.5f}" for x in xs) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+")
    ap.add_argument("--out", default=os.path.join(ROOT, "lib", "robolab", "skills", "bat_program.w"))
    ap.add_argument("--tick", type=float, default=0.005)
    a = ap.parse_args()
    docs = [json.load(open(p)) for p in a.runs]
    joints = list(docs[0]["controls"].keys())
    knots = docs[0]["knots_s"]
    for d in docs:
        assert list(d["controls"].keys()) == joints and d["knots_s"] == knots, "runs differ in joints or knots"
    # each program's pitch: its crossing (x from the plate centre, z) and the
    # ball's speed at the plate front predicted from its state at the capture
    # (the skill's predict(): quadratic drag k = 0.0062 /m along the path)
    locs = []
    for d in docs:
        x, z = (d["pitch_def"][1], d["pitch_def"][2]) if d.get("pitch_def") else pitch_location(d["seed"])
        bx, by, bz, vx, vy, vz = d["ball_state"]
        sp = float(np.linalg.norm([vx, vy, vz]))
        dy = PLATE_FRONT_Y - by
        locs.append((x, z, sp * np.exp(-0.0062 * dy * sp / vy)))
    locs = np.array(locs)
    # programs all at one pitch speed carry no speed information: blend by
    # the crossing alone
    speed_scale = SPEED_SCALE if np.ptp(locs[:, 2]) > 0.5 else 0.0
    # trajectory: displacement from the start, every tick from 0 to the shortest run's end
    t_end = min(d["timeline"][-1]["t"] for d in docs)
    ts = np.arange(0.0, t_end + 1e-9, a.tick)
    U, Q, TC = [], [], []
    for d in docs:
        U.append(np.array([d["controls"][j] for j in joints]))                 # J x K
        rows = d["timeline"]
        tt = np.array([0.0] + [r["t"] for r in rows])
        disp = []
        for j in joints:
            q = np.array([d["q_start"][j]] + [r["q_" + j] for r in rows])
            disp.append(np.interp(ts, tt, q - d["q_start"][j]))
        Q.append(np.array(disp))                                                # J x M
        TC.append(d["result"]["t"])
    n = len(docs)
    speeds = [d["result"]["speed"] for d in docs]
    src = ", ".join(os.path.relpath(p, ROOT) for p in a.runs)
    lines = [
        "# Generated by playground/bat_program_export.py; do not edit by hand.",
        f"# Sources: {src}",
        f"# Ideal-control swings (playground/bat_ceiling.py): sweet-spot speeds {speeds} m/s at",
        f"# pitches {[tuple(round(float(v), 3) for v in l) for l in locs]} (x from the plate centre, z,",
        "# speed at the plate front, m/s).",
        "# Per program (one per pitch, `locs` as x, z, v triples): u, the net",
        "# excitation per joint and knot (+ the pos muscle, - the neg), J x K; q, the",
        "# joint displacement (rad) from the program's start every `tick` s, J x M;",
        "# q_start, the joint angles it started from (N x J); t_contact, when its",
        "# sweet spot met the pitch (program clock, which starts",
        "# `lead` s before the hips fire). The skill blends the programs by inverse",
        "# squared distance to the predicted pitch (x, z and speed_scale x v; exact at",
        "# a program's own pitch).",
        "+ BatProgram",
        "  -> .joints",
        "    [" + ", ".join(f'"{j}"' for j in joints) + "]",
        "",
        "  -> .lead",
        f"    ~{float(docs[0].get('lead', 0.02)):.4f}",
        "",
        "  -> .count",
        f"    {n}",
        "",
        "  -> .locs",
        "    " + fmt([v for l in locs for v in l]),
        "",
        "  -> .speed_scale",
        f"    ~{speed_scale:.4f}",
        "",
        "  -> .t_contact",
        "    " + fmt(TC),
        "",
        "  -> .knots",
        "    " + fmt(knots),
        "",
        "  -> .tick",
        f"    ~{a.tick:.4f}",
        "",
        "  -> .q_start",
        "    " + fmt([d["q_start"][j] for d in docs for j in joints]),
        "",
        "  -> .u",
        "    " + fmt(np.array(U).ravel()),
        "",
        "  -> .q",
        "    " + fmt(np.array(Q).ravel()),
        "",
    ]
    with open(a.out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", a.out, f"({len(joints)} joints, {len(knots)} knots, {len(ts)} samples, {n} runs)")


if __name__ == "__main__":
    main()
