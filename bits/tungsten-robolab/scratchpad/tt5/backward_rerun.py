#!/usr/bin/env python3
"""Re-run the plans a SELECTION RULE picked from the backward-planning sweep (out/tt5/bwd.jsonl, rule R2: reached, then best margin) under a different oracle configuration, without re-selecting:
a hand-held paddle (no weld), a weaker servo (o2_omega), ... The plans are regenerated by backward_plan.candidates (deterministic) and matched by (offset, kind, speed).
    .venv-myo/bin/python scratchpad/tt5/backward_rerun.py LABEL --modes o1,o5,o7 [--cfg '{"o2_omega":60}'] [--sets valid,setb] [--src out/tt5/bwd.jsonl] [--sig-p 0 --sig-v 0]       from bits/tungsten-robolab"""
import argparse
import json
import os
import sys

ap = argparse.ArgumentParser()
ap.add_argument("label")
ap.add_argument("--modes", default="o1,o5,o6,o7")
ap.add_argument("--cfg", default="{}")
ap.add_argument("--sets", default="valid,setb")
ap.add_argument("--src", default="out/tt5/bwd.jsonl")
ap.add_argument("--sig-p", type=float, default=0.0)
ap.add_argument("--sig-v", type=float, default=0.0)
ap.add_argument("--workers", type=int, default=6)
ap.add_argument("--speed0", action="store_true", help="select among the still-pad candidates only (retreat speed 0)")
ap.add_argument("--set", default="", help="params name=value,... (grip variants)")
ap.add_argument("--grip", choices=["champion", "searched"], default="champion", help="searched = the best grip of the 2 Oct grasp search (scratchpad/tt4/gs_state.json)")
a = ap.parse_args()
base = {"o5_togo": 1, "o5_tact": 0.15, "o5_hold": 0.03, "o5_wrot": 0.30, "o5_lead": 0.05, "o5_hold_alpha": 0.6, "o1_margin": 0.15, "o6_ton": 0.0, "o5_mus_off": 1}
base.update(json.loads(a.cfg))
os.environ["MYO_TT_ORACLE"] = a.modes
os.environ["TT3_CFG"] = json.dumps(base)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
import backward_plan as bp  # noqa: E402
import numpy as np  # noqa: E402


def select(rows):
    by = {}
    for r in rows:
        if r.get("error") or not r.get("perr") or (a.speed0 and r.get("speed") != 0.0):
            continue
        pe = r["perr"]
        r["pos"], r["ang"] = 100 * float(np.linalg.norm(pe[:3])), float(pe[3])
        r["reached"] = r["pos"] <= 1.5 and r["ang"] <= 2.5
        r["err"] = r["pos"] / 1.5 + r["ang"] / 2.5
        by.setdefault(r["seed"], []).append(r)
    ch = {}
    for sd, c in by.items():
        ch[sd] = max([r for r in c if r["reached"]], key=lambda r: r["margin"]) if any(r["reached"] for r in c) else min(c, key=lambda r: r["err"])
    return ch


def main():
    import tt_fast
    rows = [json.loads(l) for l in open(a.src)]
    ch = select(rows)
    params = tt_fast.read_params(bp.PARAMS)
    if a.grip == "searched":
        names = ["g_fpl", "g_op", "g_text", "g_idx", "g_idx_int", "g_mid", "g_ring", "g_fext", "grip_drive", "grip_ramp", "bh_grip", "bh_grip_drive"]
        for n_, v_ in zip(names, json.load(open("scratchpad/tt4/gs_state.json"))["best"]["x"]):
            params[n_] = float(v_)
    for kv in filter(None, a.set.split(",")):
        k_, v_ = kv.split("=")
        params[k_] = float(v_)
    ctl = os.path.abspath(bp.CONTROLLER)
    seeds = [s for name in a.sets.split(",") for s in bp.seeds_of(name) if s in ch]
    jobs, meta = [], []
    for sd in seeds:
        want = ch[sd]
        plan = next(c["plan"] for c in bp.candidates(sd, a.sig_p, a.sig_v) if c["off"] == want["off"] and c["kind"] == want["kind"] and c["speed"] == want["speed"])
        jobs.append((params, sd, None, ctl, {"orc_plan": plan}))
        meta.append(want)
    pool = tt_fast.pool(a.workers)
    res = list(pool.imap(tt_fast.episode, jobs, chunksize=1))
    out = []
    for m, r in zip(meta, res):
        out.append(dict(seed=m["seed"], off=m["off"], kind=m["kind"], solved=r.get("solved"), hit=r.get("hit"), perr=r.get("o5_pad_err_last"), err=r.get("error"), tau_pk=r.get("o2_tau_peak"), tau_rms=r.get("o2_tau_rms"), palm_err_max=r.get("palm_err_max"), t_contact=r.get("t_contact"), paddle_speed=r.get("paddle_speed"), qlast=r.get("o5_q_last"), t_hit=m.get("t_hit")))
    json.dump(out, open(f"out/tt5/rerun_{a.label}.json", "w"))
    for name in a.sets.split(","):
        ss = [o for o in out if o["seed"] in set(bp.seeds_of(name))]
        k = sum(1 for o in ss if (o["solved"] or 0) > 0)
        t = sum(1 for o in ss if (o["hit"] or 0) > 0)
        print(f"{a.label} [{a.modes} {a.cfg} grip {a.grip}{(" " + a.set) if a.set else ""} noise p{a.sig_p} v{a.sig_v}] {name}: solved {k} of {len(ss)} = {100 * k / max(len(ss), 1):.0f} %, touched {t}", flush=True)


if __name__ == "__main__":
    main()
