#!/usr/bin/env python3
"""Print the arena board as a Markdown table with each champion's frozen artifacts.

    .venv/bin/python tools/arena_board_md.py > HANDOFF_20260929_board.md

Same decoding as `playground/arena.py board`: failed guards and crashes score +-1e9, so the
champion's value is the mean over the rollouts that passed, shown beside the pass count.
"""
import json
import os
import sys
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ARENA = os.path.join(ROOT, "playground", "arena")
trials = json.load(open(os.path.join(ARENA, "trials.json")))
champs = json.load(open(os.path.join(ARENA, "champions.json")))


def cell(s, n=None):
    s = str(s).replace("|", "/").replace("\n", " ")
    return s if n is None or len(s) <= n else s[: n - 3] + "..."


print(f"# Arena board, {time.strftime('%Y-%m-%d %H:%M')}")
print()
print("Generated by `tools/arena_board_md.py`. Value = mean over the rollouts that passed their guards; "
      "`pass` = passed / starts. Higher is better unless the metric is a time or an error.")
print()
print("| trial | metric | champion | pass | approach | frozen controller | frozen params |")
print("| --- | --- | ---: | ---: | --- | --- | --- |")
for name in sorted(trials):
    t = trials[name]
    c = champs.get(name)
    if not c:
        print(f"| `{name}` | {t['metric']} | (none) | | | | |")
        continue
    ok = [x for x in c.get("scores", []) if abs(x) < 1e8]
    n = len(c.get("scores", [])) or c["summary"]["n"]
    v = f"{sum(ok) / len(ok):.4g}" if ok else "nan"
    print(f"| `{name}` | {t['metric']} | {v} | {len(ok)}/{n} | {cell(c['note'], 230)} | "
          f"`{c.get('frozen_controller', '')}` | `{c.get('frozen_params', '')}` |")
