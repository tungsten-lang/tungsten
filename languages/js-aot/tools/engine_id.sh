#!/bin/sh
# engine_id.sh — writes runtime/unit_id.w: a hash of everything a compiled unit must agree
# with its host on (the frontend, the analysis, the translator, the unit prelude, the
# runtime). jsc puts it in each unit's manifest and the host loads only units with its own.
# Run before building jsc or syncing Blade (tools/sync_blade.sh runs it).
D="$(cd "$(dirname "$0")/.." && pwd)"
cd "$D"
id=$(ls frontend/*.w analyze.w translate/*.w unit/prelude.w runtime/*.w | grep -v "runtime/unit_id.w" | xargs cat | shasum -a 256 | cut -c1-16)
new="# runtime/unit_id — generated by tools/engine_id.sh; do not edit.
JSU_ENGINE_ID = \"$id\""
[ "$(cat runtime/unit_id.w 2>/dev/null)" = "$new" ] || printf '%s\n' "$new" > runtime/unit_id.w
echo "$id"
