#!/usr/bin/env python3
# gen_unit_rt — writes runtime/unit_rt.w: the host closures units call (runtime/units.w).
#
# Every runtime entry the translator can emit (string literals "js_…" in translate/*.w,
# plus the inline-cache _t forms and unit.w's own) gets one closure per arity it can be
# called with, keyed "name/arity". Run it after the translator or the runtime's
# signatures change (and bump JSU_ABI in translate/unit.w when the contract does).
import glob, os, re
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = set()
for f in glob.glob(os.path.join(D, "translate", "*.w")):
    names |= set(re.findall(r'"(js_[a-z0-9_]+[?!]?)"', open(f).read()))
names |= {"js_getp_t", "js_setp_t", "js_call_method_t", "js_new_t", "js_env_new", "js_envn_new",
          "js_private_name_new", "js_object_proto"}
names -= {"js_getp", "js_setp", "js_call_method", "js_new"}   # always called as _t forms
defs = {}
for f in sorted(glob.glob(os.path.join(D, "runtime", "*.w"))):
    for m in re.finditer(r"^-> (js_[a-z0-9_]+[?!]?)(?:\((.*)\))?\s*$", open(f).read(), re.M):
        ps = [p.strip() for p in m.group(2).split(",")] if m.group(2) else []
        req = len([p for p in ps if "=" not in p])
        defs.setdefault(m.group(1), (req, len(ps)))
missing = sorted(n for n in names if n not in defs)
lines = ["# runtime/unit_rt — generated by tools/gen_unit_rt.py; do not edit.",
         "#",
         "# The host closures a compiled unit calls, keyed \"name/arity\" (runtime/units.w).",
         "",
         "JSU_RT = {"]
entries = []
for n in sorted(names):
    if n not in defs:
        continue
    req, tot = defs[n]
    for k in range(req, tot + 1):
        ps = ", ".join("a%d" % i for i in range(k))
        entries.append('  "%s/%d" => ->(%s) %s(%s)' % (n, k, ps, n, ps))
lines.append(",\n".join(entries))
lines.append("}")
open(os.path.join(D, "runtime", "unit_rt.w"), "w").write("\n".join(lines) + "\n")
print("%d entries; not in the runtime: %s" % (len(entries), ", ".join(missing) or "none"))
