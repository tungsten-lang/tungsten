#!/usr/bin/env python3
"""Generate bits/tungsten-llama/lib/tokenizer_categories.w — flattened
[start, end] codepoint ranges for the Unicode categories the qwen2
pretokenizer needs (L=letters, M=marks, N=numbers), from this Python's
unicodedata. Whitespace is the fixed Onig \\s set, inlined in tokenizer.w.
"""

import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    try:
        return unicodedata.category(chr(cp))
    except ValueError:
        return "Cn"


def emit(name, rs, f):
    f.write(f"{name} = [")
    parts = []
    for a, b in rs:
        parts.append(f"{a}, {b}")
    f.write(", ".join(parts))
    f.write("]\n")


def main():
    out = "bits/tungsten-llama/lib/tokenizer_categories.w"
    with open(out, "w") as f:
        f.write("# GENERATED by scripts/bench/gen_tok_categories.py — do not edit.\n")
        f.write(f"# Unicode {unicodedata.unidata_version} category ranges "
                "(flattened start,end pairs) for the qwen2 pretokenizer.\n\n")
        L = ranges(lambda cp: cat(cp).startswith("L"))
        M = ranges(lambda cp: cat(cp).startswith("M"))
        N = ranges(lambda cp: cat(cp).startswith("N"))
        emit("TOK_CAT_L", L, f)
        emit("TOK_CAT_M", M, f)
        emit("TOK_CAT_N", N, f)
        print(f"L ranges: {len(L)}, M: {len(M)}, N: {len(N)} -> {out}")


if __name__ == "__main__":
    main()
