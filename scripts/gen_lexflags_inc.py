#!/usr/bin/env python3
"""Embed languages/tungsten/tungsten.lex64 and .lex32 in the runtime.

The runtime loads the Tungsten lexer's per-codepoint flag tables from
languages/tungsten/ (cwd, $TUNGSTEN_ROOT, or next to the runtime). A program
that embeds the lexer and runs without a toolchain checkout has none of those,
so runtime.c rebuilds the tables from this run-length copy instead.

    python3 scripts/gen_lexflags_inc.py            # write runtime/tungsten_lexflags.inc
    python3 scripts/gen_lexflags_inc.py --check    # fail if it is stale
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "runtime", "tungsten_lexflags.inc")


def runs(data):
    out = []
    start = 0
    for i in range(1, len(data) + 1):
        if i == len(data) or data[i] != data[start]:
            if data[start] != 0:
                out.append((start, i - start, data[start]))
            start = i
    return out


def table(name, path):
    data = open(path, "rb").read()
    rs = runs(data)
    lines = ["static const uint32_t %s[][3] = {  /* start, length, flags */" % name]
    row = []
    for r in rs:
        row.append("{%d,%d,%d}" % r)
        if len(row) == 8:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    lines.append("#define %s_N %d" % (name.upper(), len(rs)))
    return "\n".join(lines)


def generate():
    base = os.path.join(ROOT, "languages", "tungsten", "tungsten")
    parts = [
        "/* Generated by scripts/gen_lexflags_inc.py from languages/tungsten/tungsten.lex64",
        " * and tungsten.lex32. Do not edit. Non-zero runs only; every other codepoint is 0. */",
        table("w_tungsten_lex64_runs", base + ".lex64"),
        table("w_tungsten_lex32_runs", base + ".lex32"),
        "",
    ]
    return "\n".join(parts)


def main():
    text = generate()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("runtime/tungsten_lexflags.inc is stale; run python3 scripts/gen_lexflags_inc.py")
        print("runtime/tungsten_lexflags.inc is up to date")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote " + OUT)


if __name__ == "__main__":
    main()
